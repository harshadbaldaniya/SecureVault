"""Prints the database design as Mermaid entity-relationship diagrams, generated from the Django models.

The diagrams in docs/database-design.md are produced by this command, and a test fails if the committed file no longer
matches the models, so the documentation cannot silently drift from the schema.

    python manage.py er_diagram > docs/er-diagram.md
"""

from django.apps import apps
from django.core.management.base import BaseCommand
from django.db import models

# Diagram title -> (description, model labels "app.Model")
GROUPS = {
    "Identity, organization and policy": (
        "Who exists, which organization they belong to, how they sign in, and the organization's rules.",
        [
            "organizations.Organization",
            "accounts.User",
            "accounts.Invitation",
            "accounts.UserSession",
            "accounts.TOTPDevice",
            "accounts.RecoveryCode",
            "accounts.PasswordResetToken",
            "departments.Department",
            "policies.SecurityPolicy",
            "services_catalog.ServiceCatalog",
        ],
    ),
    "Vault, sharing and access requests": (
        "Encrypted items, the keys that protect them, delegated access and the requests that lead to it.",
        [
            "vault.OrganizationKey",
            "vault.Credential",
            "vault.SecureNote",
            "sharing.Share",
            "access_requests.AccessRequest",
        ],
    ),
    "Devices, anomalies, lockdown and notifications": (
        "Zero-trust signals and controls.",
        [
            "devices.Device",
            "devices.DeviceEvent",
            "devices.AnomalyAlert",
            "lockdown.LockdownState",
            "notifications.Notification",
        ],
    ),
    "Audit and imports": (
        "The tamper-evident trail and bulk onboarding.",
        ["audit.AuditChainHead", "audit.AuditLog", "imports.ImportJob"],
    ),
}

TYPES = [
    (models.UUIDField, "uuid"),
    (models.BooleanField, "bool"),
    (models.DateTimeField, "datetime"),
    (models.DateField, "date"),
    (models.JSONField, "json"),
    (models.BinaryField, "bytes"),
    (models.FloatField, "float"),
    (models.IntegerField, "int"),  # also covers BigInteger, PositiveSmallInteger, AutoField subclasses
    (models.GenericIPAddressField, "ip"),
]


def type_name(field) -> str:
    if isinstance(field, models.ForeignKey | models.OneToOneField):
        return type_name(field.target_field)
    for klass, name in TYPES:
        if isinstance(field, klass):
            return name
    if getattr(field, "base_field", None) is not None:
        return f"{type_name(field.base_field)}_array"
    return "string"


def entity(model) -> str:
    return model.__name__


class Command(BaseCommand):
    help = "Print Mermaid ER diagrams generated from the models."

    def handle(self, *args, **options):
        out = ["# Entity-relationship diagrams", "", "<!-- Generated by `manage.py er_diagram`; do not edit. -->", ""]
        for title, (description, labels) in GROUPS.items():
            members = [apps.get_model(label) for label in labels]
            out += [f"## {title}", "", description, "", "```mermaid", "erDiagram"]
            relations = []
            for model in members:
                out.append(f"    {entity(model)} {{")
                for field in model._meta.concrete_fields:
                    flags = []
                    if field.primary_key:
                        flags.append("PK")
                    if isinstance(field, models.ForeignKey | models.OneToOneField):
                        flags.append("FK")
                        target = field.related_model
                        label = field.name
                        left = "|o" if field.null else "||"
                        right = "o|" if isinstance(field, models.OneToOneField) else "o{"
                        relations.append(f'    {entity(target)} {left}--{right} {entity(model)} : "{label}"')
                    if field.unique and not field.primary_key:
                        flags.append("UK")
                    out.append(f"        {type_name(field)} {field.name}" + (f" {', '.join(flags)}" if flags else ""))
                out.append("    }")
            out += sorted(set(relations))
            out += ["```", ""]
        self.stdout.write("\n".join(out))
